		<p class="is-style-muted">Professor Malandro, <strong>Alfredo Juliano Prince</strong>, inició su camino en la capoeira en <strong class="text-yellow">2005</strong> en la University of the Virgin Islands. Más tarde continuó su desarrollo en <strong>Cuernavaca, Morelos</strong>, donde ha formado parte de la comunidad capoeirista local desde 2009.</p>
		<!-- /wp:paragraph -->
		<!-- wp:paragraph {"className":"is-style-muted"} -->
		<p class="is-style-muted">Entrenó con <strong>Ginga no Guetto</strong> hasta 2016 y ese mismo año comenzó su camino con <strong>Mestre Madona y Pura Capoeira</strong>. En septiembre de 2017 completó su formación como instructor en Cuernavaca durante el 2º Circuito Nacional. En 2022 recibió su primer grado de Professor en Guanajuato, y en diciembre de 2024 recibió su segundo grado de Professor en Caucaia, Ceará, Brasil.</p>
		<!-- /wp:paragraph -->
		<!-- wp:paragraph {"className":"is-style-muted"} -->
		<p class="is-style-muted">Ha enseñado capoeira desde 2015 y ha compartido esta arte en <strong>México, las Islas Vírgenes, Fortaleza y Caucaia</strong>. Hoy dirige Pura Capoeira Cuernavaca.</p>
		<!-- /wp:paragraph -->
		<!-- wp:paragraph {"className":"is-style-muted"} -->
		<p class="is-style-muted">Su enfoque parte de una idea simple: la capoeira te muestra quién eres cuando algo te cuesta, y te da la oportunidad de responder mejor. Por eso en sus clases importan tanto la técnica y la música como la constancia, el respeto por el compañero y la honestidad con uno mismo. Ese compromiso lo asume también como profesor.</p>
